#!/usr/bin/env python3
"""Generates library/runtime/unicode.c from the Unicode Character Database.

The runtime classifies and case-maps characters with these tables instead of
the C library, so every target gives the same answers and the runtime never
has to change the process locale.

    curl -O https://www.unicode.org/Public/16.0.0/ucd/UnicodeData.txt
    curl -O https://www.unicode.org/Public/16.0.0/ucd/SpecialCasing.txt
    python3 tools/unicode/generate.py UnicodeData.txt SpecialCasing.txt \
        > library/runtime/unicode.c
"""

import sys

VERSION = "16.0.0"

# The White_Space property from PropList.txt. It hasn't changed since
# Unicode 6.0, so it is listed here instead of parsing a second file.
WHITE_SPACE = [
    (0x0009, 0x000D), (0x0020, 0x0020), (0x0085, 0x0085), (0x00A0, 0x00A0),
    (0x1680, 0x1680), (0x2000, 0x200A), (0x2028, 0x2029), (0x202F, 0x202F),
    (0x205F, 0x205F), (0x3000, 0x3000),
]


def read(path):
    categories = {}
    upper = {}
    lower = {}
    first = None
    with open(path, encoding="utf-8") as data:
        for line in data:
            fields = line.rstrip("\n").split(";")
            code = int(fields[0], 16)
            name, category = fields[1], fields[2]
            if name.endswith(", First>"):
                first = code
                continue
            start = first if name.endswith(", Last>") else code
            first = None
            for c in range(start, code + 1):
                categories[c] = category
            if fields[12]:
                upper[code] = int(fields[12], 16)
            if fields[13]:
                lower[code] = int(fields[13], 16)
    return categories, upper, lower


def read_special(path):
    """The unconditional entries of SpecialCasing.txt: characters whose full
    case mapping is more than one character, like `ß` -> `SS`."""
    upper = {}
    lower = {}
    with open(path, encoding="utf-8") as data:
        for line in data:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            fields = [field.strip() for field in line.split(";")]
            if fields[4]:
                continue  # language- or context-dependent
            code = int(fields[0], 16)
            for table, field in ((lower, fields[1]), (upper, fields[3])):
                chars = [int(part, 16) for part in field.split()]
                if chars != [code]:
                    table[code] = chars
    return upper, lower


def ranges(codes):
    out = []
    for c in sorted(codes):
        if out and out[-1][1] == c - 1:
            out[-1][1] = c
        else:
            out.append([c, c])
    return out


def emit_ranges(name, spans):
    print(f"static const KrRange {name}[] = {{")
    for lo, hi in spans:
        print(f"    {{0x{lo:05X}, 0x{hi:05X}}},")
    print("};\n")


def emit_mapping(name, mapping):
    print(f"static const KrMapping {name}[] = {{")
    for code in sorted(mapping):
        print(f"    {{0x{code:05X}, 0x{mapping[code]:05X}}},")
    print("};\n")


def emit_special(name, mapping):
    print(f"static const KrSpecial {name}[] = {{")
    for code in sorted(mapping):
        chars = mapping[code] + [0] * (3 - len(mapping[code]))
        rendered = ", ".join(f"0x{c:05X}" for c in chars)
        print(f"    {{0x{code:05X}, {len(mapping[code])}, {{{rendered}}}}},")
    print("};\n")


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    categories, upper, lower = read(sys.argv[1])
    special_upper, special_lower = read_special(sys.argv[2])
    of = lambda test: ranges(c for c, cat in categories.items() if test(cat))

    print(f"/* Generated by tools/unicode/generate.py from UnicodeData.txt {VERSION}. Do not edit. */\n")
    print('#include "krelpin.h"\n')
    print("typedef struct {\n    int32_t lo;\n    int32_t hi;\n} KrRange;\n")
    print("typedef struct {\n    int32_t from;\n    int32_t to;\n} KrMapping;\n")
    print("typedef struct {\n    int32_t from;\n    int32_t len;\n    int32_t to[3];\n} KrSpecial;\n")
    emit_ranges("letters", of(lambda cat: cat.startswith("L")))
    emit_ranges("digits", of(lambda cat: cat == "Nd"))
    emit_ranges("uppercase", of(lambda cat: cat == "Lu"))
    emit_ranges("lowercase", of(lambda cat: cat == "Ll"))
    emit_ranges("white_space", WHITE_SPACE)
    emit_mapping("to_upper", upper)
    emit_mapping("to_lower", lower)
    emit_special("full_upper", special_upper)
    emit_special("full_lower", special_lower)
    print(BODY)


BODY = """\
#define COUNT(table) ((int64_t)(sizeof(table) / sizeof((table)[0])))

static bool in_ranges(const KrRange *table, int64_t count, int32_t c) {
    int64_t lo = 0;
    int64_t hi = count;
    while (lo < hi) {
        int64_t mid = lo + (hi - lo) / 2;
        if (c < table[mid].lo) {
            hi = mid;
        } else if (c > table[mid].hi) {
            lo = mid + 1;
        } else {
            return true;
        }
    }
    return false;
}

static int32_t mapped(const KrMapping *table, int64_t count, int32_t c) {
    int64_t lo = 0;
    int64_t hi = count;
    while (lo < hi) {
        int64_t mid = lo + (hi - lo) / 2;
        if (c < table[mid].from) {
            hi = mid;
        } else if (c > table[mid].from) {
            lo = mid + 1;
        } else {
            return table[mid].to;
        }
    }
    return c;
}

bool kr_char_is_digit(int32_t c) {
    return c < 128 ? c >= '0' && c <= '9' : in_ranges(digits, COUNT(digits), c);
}

bool kr_char_is_letter(int32_t c) {
    if (c < 128) {
        return (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z');
    }
    return in_ranges(letters, COUNT(letters), c);
}

bool kr_char_is_whitespace(int32_t c) {
    return in_ranges(white_space, COUNT(white_space), c);
}

bool kr_char_is_upper(int32_t c) {
    return c < 128 ? c >= 'A' && c <= 'Z' : in_ranges(uppercase, COUNT(uppercase), c);
}

bool kr_char_is_lower(int32_t c) {
    return c < 128 ? c >= 'a' && c <= 'z' : in_ranges(lowercase, COUNT(lowercase), c);
}

int32_t kr_char_to_upper(int32_t c) {
    if (c < 128) {
        return c >= 'a' && c <= 'z' ? c - 32 : c;
    }
    return mapped(to_upper, COUNT(to_upper), c);
}

int32_t kr_char_to_lower(int32_t c) {
    if (c < 128) {
        return c >= 'A' && c <= 'Z' ? c + 32 : c;
    }
    return mapped(to_lower, COUNT(to_lower), c);
}

static const KrSpecial *special(const KrSpecial *table, int64_t count, int32_t c) {
    int64_t lo = 0;
    int64_t hi = count;
    while (lo < hi) {
        int64_t mid = lo + (hi - lo) / 2;
        if (c < table[mid].from) {
            hi = mid;
        } else if (c > table[mid].from) {
            lo = mid + 1;
        } else {
            return &table[mid];
        }
    }
    return NULL;
}

int32_t kr_char_to_upper_full(int32_t c, int32_t out[3]) {
    const KrSpecial *entry = c < 128 ? NULL : special(full_upper, COUNT(full_upper), c);
    if (entry == NULL) {
        out[0] = kr_char_to_upper(c);
        return 1;
    }
    for (int32_t i = 0; i < entry->len; i++) {
        out[i] = entry->to[i];
    }
    return entry->len;
}

int32_t kr_char_to_lower_full(int32_t c, int32_t out[3]) {
    const KrSpecial *entry = c < 128 ? NULL : special(full_lower, COUNT(full_lower), c);
    if (entry == NULL) {
        out[0] = kr_char_to_lower(c);
        return 1;
    }
    for (int32_t i = 0; i < entry->len; i++) {
        out[i] = entry->to[i];
    }
    return entry->len;
}"""

if __name__ == "__main__":
    main()
